import react from "@vitejs/plugin-react";
import { dts } from "rolldown-plugin-dts";
import { defaultClientConditions, defineConfig, esmExternalRequirePlugin } from "vite";
import pkg from "./package.json" with { type: "json" };

// The host app installs the dependencies and provides the peers, so that all instances share one copy
// of them and the declarations reference their types instead of inlining them.
// Their subpaths, e.g. react/jsx-runtime or @mui/material/styles, are external as well.
const externals = Object.keys({ ...pkg.dependencies, ...pkg.peerDependencies }).map(
  (dep) => new RegExp(`^${RegExp.escape(dep)}(/|$)`),
);

// Declarations generated by rolldown-plugin-dts, which must not be transformed as TypeScript.
const declarations = /\.d\.[cm]?ts$/;

// CORS proxies for the dev server, mirroring the proxy routes of the Caddyfile and netlify.toml.
const proxies = {
  "/api/aifdb": "https://aifdb.org",
  "/api/wikipedia": "https://api.wikimedia.org",
};

// Two build modes, each with its own output directory, since Vite empties `outDir` on every build:
//   - default:     the standalone single-page app      -> dist/app
//   - --mode lib:  the embeddable library (ESM + .d.ts) -> dist/lib
export default defineConfig(({ mode }) => {
  const isLib = mode === "lib";

  return {
    plugins: [
      // The React plugin makes Vite's Oxc transform every file matching its filter,
      // regardless of `oxc.exclude`, so declarations are excluded here as well.
      react({ exclude: [/\/node_modules\//, declarations] }),
      ...(isLib
        ? [
            // Bundles the declarations that Oxc emits thanks to `isolatedDeclarations`,
            // which only the app config enables (the root config just references it).
            dts({ tsconfig: "tsconfig.app.json" }),
            // Marks the packages external and, unlike build.rolldownOptions.external, rewrites
            // `require` calls of bundled CommonJS code for them into ESM imports.
            // Browsers have no `require`, so those calls would throw at runtime.
            esmExternalRequirePlugin({ external: externals }),
          ]
        : []),
    ],
    // Assets of the library such as the layout worker are referenced relative to it, not to the host root.
    base: isLib ? "./" : undefined,
    // Keeps the generated declarations away from the TS transform, as rolldown-plugin-dts requires.
    oxc: isLib ? { exclude: [/\.js$/, declarations] } : undefined,
    server: {
      proxy: Object.fromEntries(
        Object.entries(proxies).map(([prefix, target]) => [
          prefix,
          { target, changeOrigin: true, rewrite: (path: string) => path.slice(prefix.length) },
        ]),
      ),
    },
    build: {
      outDir: isLib ? "dist/lib" : "dist/app",
      chunkSizeWarningLimit: 5000,
      // public/ holds the standalone app's favicon, manifest and robots.txt,
      // none of which belong in a library bundle.
      copyPublicDir: !isLib,
      lib: isLib ? { entry: { lib: "src/lib.ts" }, formats: ["es"] } : false,
    },
    resolve: {
      tsconfigPaths: true,
      // Opts into the modern MUI bundle, see
      // https://mui.com/material-ui/guides/minimizing-bundle-size/.
      conditions: ["mui-modern", ...defaultClientConditions],
    },
  };
});
